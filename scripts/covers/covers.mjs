// ---------- 投影与原语 ----------
const OX = 0, OY = 0, KX = 0.5, KY = -0.35   // 原点是底座顶面左前角；进深每单位往右 0.5、往上 0.35。整张再由 FIT 放大、挪到画面中间
const f = n => String(Math.round(n * 10) / 10)
const P = (x, y, z) => [OX + x + y * KX, OY - z + y * KY]
const PV = (x, y, z) => [x + y * KX, -z + y * KY]
const xy = ([x, y]) => f(x) + ' ' + f(y)
const cl = c => (c ? ` class="${c}"` : '')
const path = (c, d, extra = '') => `<path${cl(c)}${extra} d="${d}"/>`
/** 多边形（三维点） */
const poly = (pts, c) => path(c, 'M' + pts.map(p => xy(P(...p))).join('L') + 'z')
/** 折线（三维点） */
const line = (pts, c = '') => path(c, 'M' + pts.map(p => xy(P(...p))).join('L'))
/** 盒子：顶、右、正三面 */
const box = (x0, x1, y0, y1, z0, z1, { t = 'w', fr = 'g2', r = 'g3' } = {}) => [
  poly([[x0, y0, z1], [x1, y0, z1], [x1, y1, z1], [x0, y1, z1]], t),
  poly([[x1, y0, z0], [x1, y1, z0], [x1, y1, z1], [x1, y0, z1]], r),
  poly([[x0, y0, z0], [x1, y0, z0], [x1, y0, z1], [x0, y0, z1]], fr),
].join('')
/** 拉伸截面：sec 是 xz 平面上逆时针的点，沿 y 从 y0 拉到 y1。看得见的侧面按朝向上色，正面盖子最后画 */
const prism = (sec, y0, y1, { fr = 'g2', t = 'w', side = 'g1', r = 'g3' } = {}) => {
  let s = ''
  sec.forEach((a, i) => {
    const b = sec[(i + 1) % sec.length], nx = b[1] - a[1], nz = a[0] - b[0], L = Math.hypot(nx, nz)
    if (0.5 * nx + 0.35 * nz <= 0.01) return
    s += poly([[a[0], y0, a[1]], [b[0], y0, b[1]], [b[0], y1, b[1]], [a[0], y1, a[1]]], nz / L > 0.8 ? t : nx / L > 0.8 ? r : side)
  })
  return s + poly(sec.map(([x, z]) => [x, y0, z]), fr)
}
/** 由两条共轭半径算椭圆参数（屏幕坐标） */
const ellP = (u, v) => {
  const a = u[0] ** 2 + v[0] ** 2, b = u[0] * u[1] + v[0] * v[1], c = u[1] ** 2 + v[1] ** 2
  const m = (a + c) / 2, d = Math.sqrt(((a - c) / 2) ** 2 + b * b)
  return { rx: Math.sqrt(m + d), ry: Math.sqrt(Math.max(m - d, 0)), deg: (Math.atan2(2 * b, a - c) / 2) * 180 / Math.PI }
}
const ell = (c3, u3, v3, c) => {
  const [cx, cy] = P(...c3), { rx, ry, deg } = ellP(PV(...u3), PV(...v3))
  return `<ellipse${cl(c)} cx="${f(cx)}" cy="${f(cy)}" rx="${f(rx)}" ry="${f(ry)}" transform="rotate(${f(deg)} ${f(cx)} ${f(cy)})"/>`
}
/** 水平圆（在 z 高度上） */
const disc = (x, y, z, r, c) => ell([x, y, z], [r, 0, 0], [0, r, 0], c)
/** 竖直圆柱：侧面 + 顶面；open 为 true 时只画轮廓（玻璃） */
const cyl = (x, y, z0, z1, r, { side = 'g1', t = 'w', open = false } = {}) => {
  const u = PV(r, 0, 0), v = PV(0, r, 0), { rx, ry, deg } = ellP(u, v)
  const k = Math.atan2(v[0], u[0]), ex = u[0] * Math.cos(k) + v[0] * Math.sin(k), ey = u[1] * Math.cos(k) + v[1] * Math.sin(k)
  const [bx, by] = P(x, y, z0), [tx, ty] = P(x, y, z1)
  const d = `M${f(tx - ex)} ${f(ty - ey)}L${f(bx - ex)} ${f(by - ey)}A${f(rx)} ${f(ry)} ${f(deg)} 0 0 ${f(bx + ex)} ${f(by + ey)}L${f(tx + ex)} ${f(ty + ey)}`
  return open ? path('', d) + disc(x, y, z1, r, '') : path(side, d + 'z') + disc(x, y, z1, r, t)
}
/** 水平半圆（朝前的一半），量角器之类 */
const half = (x, y, z, r, c) => {
  const { rx, ry, deg } = ellP(PV(r, 0, 0), PV(0, r, 0))
  return path(c, `M${xy(P(x - r, y, z))}A${f(rx)} ${f(ry)} ${f(deg)} 0 0 ${xy(P(x + r, y, z))}z`)
}
/** 屏幕上的圆（球） */
const ball = (x, y, z, r, c) => { const [cx, cy] = P(x, y, z); return `<circle${cl(c)} cx="${f(cx)}" cy="${f(cy)}" r="${f(r)}"/>` }
/** 箭头：三维两点，箭头头在屏幕上画 */
const arrow = (p0, p1, c = 'c', h = 5) => {
  const [x0, y0] = P(...p0), [x1, y1] = P(...p1), a = Math.atan2(y1 - y0, x1 - x0), w = 0.5
  const q = s => [x1 - h * Math.cos(a + s * w), y1 - h * Math.sin(a + s * w)]
  return path(c, `M${xy([x0, y0])}L${xy([x1, y1])}M${xy(q(1))}L${xy([x1, y1])}L${xy(q(-1))}`)
}
/** 屏幕坐标的自由路径，以三维点为原点 */
const at = (p3, d, c) => { const [x, y] = P(...p3); return path(c, `M${f(x)} ${f(y)}` + d) }
/** 底座：每张都一样 */
